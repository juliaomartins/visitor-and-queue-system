"""The assistant's admin routes: ask, review conversations, manage memories.

Every query is scoped to `request.user`. Another admin's conversation or note
answers 404 -- the same as one that does not exist, so an id confirms nothing.
"""

import logging

import openai
from django.conf import settings
from django.db import IntegrityError
from django.db.models import Count
from drf_spectacular.utils import extend_schema
from langgraph.errors import GraphRecursionError
from rest_framework import status
from rest_framework.exceptions import NotFound
from rest_framework.response import Response
from rest_framework.throttling import ScopedRateThrottle
from rest_framework.views import APIView

from apps.common.permissions import IsAdmin

from . import agent, services
from .models import Conversation, MemoryNote
from .serializers import (
    AssistantStatusSerializer,
    ChatRequestSerializer,
    ChatResponseSerializer,
    ConversationDetailSerializer,
    ConversationRenameSerializer,
    ConversationSummarySerializer,
    MemoryNoteSerializer,
)

log = logging.getLogger(__name__)

# The history panel shows recent conversations; older ones are still stored.
LIST_LIMIT = 50

TOO_MANY_STEPS = (
    "That question took too many steps. Try asking it more narrowly, for one "
    "day or one country."
)


def _unavailable(detail: str, code: int = status.HTTP_503_SERVICE_UNAVAILABLE):
    return Response({"detail": detail}, status=code)


def _owned_conversations(user):
    return Conversation.objects.filter(owner=user).annotate(
        message_count=Count("messages")
    )


class AssistantStatusView(APIView):
    permission_classes = [IsAdmin]

    @extend_schema(
        operation_id="assistant_status_retrieve",
        summary="Whether the chat assistant is configured on this server",
        responses={200: AssistantStatusSerializer},
        tags=["assistant"],
    )
    def get(self, request):
        return Response(
            {"enabled": agent.is_configured(), "model": settings.ASSISTANT_MODEL}
        )


class AssistantChatView(APIView):
    """Answer one question about the event's data, from PostgreSQL."""

    permission_classes = [IsAdmin]
    throttle_classes = [ScopedRateThrottle]
    throttle_scope = "assistant"

    @extend_schema(
        operation_id="assistant_chat_create",
        summary="Ask the data assistant a question",
        description=(
            "Send one message, and the conversation it belongs to (omit it to start "
            "a new one). The server loads the conversation's stored history, so the "
            "assistant remembers it; the question and the answer are saved together "
            "only once the answer exists, so a failed call saves nothing and can be "
            "retried. `locale` is the dashboard's language, used only when the "
            "message is too short to tell its own.\n\n"
            "The answer is generated by an OpenAI model from rows retrieved through "
            "the same services as `/reports/entries`. Read-only, except notes the "
            "admin explicitly asks it to remember (`remembered`).\n\n"
            "`answer.downloads` lists files the answer offers. They are not attached: "
            "fetch `entrance_report` from `/reports/entries.{format}` with its filters "
            "and `visitor_list` from `/badges/roster.xlsx`.\n\n"
            "404 for a conversation that is not this admin's. 503 when no OpenAI key "
            "is configured or OpenAI is unreachable; 502 when OpenAI rejects the key "
            "or the model."
        ),
        request=ChatRequestSerializer,
        responses={200: ChatResponseSerializer},
        tags=["assistant"],
    )
    def post(self, request):
        payload = ChatRequestSerializer(data=request.data)
        payload.is_valid(raise_exception=True)
        data = payload.validated_data
        request_id = data.get("request_id")

        # A Retry of a send that already landed: answer from the database. The
        # proxy in front of us gives up long before a slow answer does.
        if request_id and (stored := services.find_exchange(request.user, request_id)):
            return self._respond(*stored, remembered=[])

        conversation = None
        if data.get("conversation"):
            try:
                conversation = services.get_owned(request.user, data["conversation"])
            except Conversation.DoesNotExist:
                raise NotFound("No such conversation.") from None

        messages = [
            *services.history(conversation),
            {"role": "user", "content": data["message"]},
        ]

        try:
            result = agent.ask(messages, actor=request.user, locale=data["locale"])
        except agent.AssistantNotConfigured:
            return _unavailable(
                "The assistant is not configured: set OPENAI_API_KEY in "
                "vms-backend/.env and restart the backend."
            )
        except openai.AuthenticationError:
            return _unavailable(
                "OpenAI rejected the API key in vms-backend/.env.",
                status.HTTP_502_BAD_GATEWAY,
            )
        except (openai.NotFoundError, openai.PermissionDeniedError):
            return _unavailable(
                f"OpenAI does not offer the model '{settings.ASSISTANT_MODEL}' to this "
                "key. Set VMS_ASSISTANT_MODEL in vms-backend/.env.",
                status.HTTP_502_BAD_GATEWAY,
            )
        except openai.RateLimitError:
            return _unavailable("OpenAI is rate-limiting this key, or it is out of credit.")
        except (openai.APIConnectionError, openai.APITimeoutError):
            return _unavailable(
                "Could not reach OpenAI. This server needs internet access for the "
                "assistant."
            )
        except GraphRecursionError:
            # An answer of sorts, and worth keeping in the conversation: the
            # admin sees why, and a rephrased follow-up has the context.
            result = {"answer": TOO_MANY_STEPS, "downloads": [], "tools_used": [], "remembered": []}
        except openai.APIError as error:
            log.warning("assistant: OpenAI error %s", error)
            return _unavailable("OpenAI returned an error. Try again in a moment.")

        try:
            conversation, question, answer = services.record_exchange(
                request.user,
                conversation,
                question=data["message"],
                locale=data["locale"],
                result=result,
                client_id=request_id,
            )
        except IntegrityError:
            # The first attempt of this same send finished while this one was
            # waiting on OpenAI. Its answer is the one already saved; return it
            # rather than saving the question a second time.
            stored = services.find_exchange(request.user, request_id) if request_id else None
            if stored is None:
                raise
            return self._respond(*stored, remembered=[])

        return self._respond(
            conversation, question, answer, remembered=result.get("remembered", [])
        )

    @staticmethod
    def _respond(conversation, question, answer, *, remembered):
        conversation.message_count = conversation.messages.count()
        return Response(
            ChatResponseSerializer(
                {
                    "conversation": conversation,
                    "question": question,
                    "answer": answer,
                    "remembered": remembered,
                }
            ).data
        )


class ConversationListView(APIView):
    permission_classes = [IsAdmin]

    @extend_schema(
        operation_id="assistant_conversations_list",
        summary="This admin's recent assistant conversations, newest first",
        responses={200: ConversationSummarySerializer(many=True)},
        tags=["assistant"],
    )
    def get(self, request):
        rows = _owned_conversations(request.user)[:LIST_LIMIT]
        return Response(ConversationSummarySerializer(rows, many=True).data)


class ConversationDetailView(APIView):
    permission_classes = [IsAdmin]

    def _get(self, request, pk) -> Conversation:
        try:
            return _owned_conversations(request.user).prefetch_related("messages").get(pk=pk)
        except Conversation.DoesNotExist:
            raise NotFound("No such conversation.") from None

    @extend_schema(
        operation_id="assistant_conversations_retrieve",
        summary="One conversation with every message",
        responses={200: ConversationDetailSerializer},
        tags=["assistant"],
    )
    def get(self, request, pk):
        return Response(ConversationDetailSerializer(self._get(request, pk)).data)

    @extend_schema(
        operation_id="assistant_conversations_partial_update",
        summary="Rename a conversation",
        description=(
            "Changes the title shown in the assistant's history. Renaming is "
            "housekeeping, not activity, so the conversation keeps its place in "
            "the list."
        ),
        request=ConversationRenameSerializer,
        responses={200: ConversationSummarySerializer},
        tags=["assistant"],
    )
    def patch(self, request, pk):
        conversation = self._get(request, pk)
        payload = ConversationRenameSerializer(data=request.data)
        payload.is_valid(raise_exception=True)

        conversation.title = payload.validated_data["title"]
        # `update_fields` keeps `auto_now` from bumping updated_at, which would
        # move a renamed conversation to the top as if it had just been used.
        conversation.save(update_fields=["title"])
        return Response(ConversationSummarySerializer(conversation).data)

    @extend_schema(
        operation_id="assistant_conversations_destroy",
        summary="Delete a conversation and its messages, for good",
        responses={204: None},
        tags=["assistant"],
    )
    def delete(self, request, pk):
        self._get(request, pk).delete()
        return Response(status=status.HTTP_204_NO_CONTENT)


class MemoryListView(APIView):
    permission_classes = [IsAdmin]

    @extend_schema(
        operation_id="assistant_memories_list",
        summary="What the assistant remembers for this admin",
        responses={200: MemoryNoteSerializer(many=True)},
        tags=["assistant"],
    )
    def get(self, request):
        notes = MemoryNote.objects.filter(owner=request.user)
        return Response(MemoryNoteSerializer(notes, many=True).data)


class MemoryDetailView(APIView):
    permission_classes = [IsAdmin]

    @extend_schema(
        operation_id="assistant_memories_destroy",
        summary="Forget one note",
        responses={204: None},
        tags=["assistant"],
    )
    def delete(self, request, pk):
        deleted, _ = MemoryNote.objects.filter(owner=request.user, pk=pk).delete()
        if not deleted:
            raise NotFound("No such note.")
        return Response(status=status.HTTP_204_NO_CONTENT)
